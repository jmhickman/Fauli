/// Build a minimal but structurally valid .ccache v4 file with one TGT credential.
let private buildMinimalCcache (serverNameComponents : string list) : byte array =
    let buf = System.Collections.Generic.List<byte>()
    let writeByte (b : byte) = buf.Add(b) |> ignore
    let writeBytes (arr : byte array) = Array.iter writeByte arr
    let writeUint16BE (v : uint16) =
        writeByte (byte (int v >>> 8 &&& 0xFF))
        writeByte (byte (int v &&& 0xFF))
    let writeUint32BE (v : uint32) =
        writeByte (byte (int v >>> 24 &&& 0xFF))
        writeByte (byte (int v >>> 16 &&& 0xFF))
        writeByte (byte (int v >>> 8 &&& 0xFF))
        writeByte (byte (int v &&& 0xFF))
    let writeCountedString (s : string) =
        let b = System.Text.Encoding.ASCII.GetBytes s
        writeUint32BE (uint32 b.Length)
        writeBytes b

    // Version 4: file_format_version = 0x0504, headerlen = 12
    // (MiniHeader is the first 4 bytes of the file)
    writeUint16BE 0x0504us
    writeUint16BE 12us

    // One header entry: tag=1, taglen=8, tagdata="TESTDATA"
    writeUint16BE 1us
    writeUint16BE 8us
    writeBytes (System.Text.Encoding.ASCII.GetBytes "TESTDATA")

    // Default principal: name_type=1, num_components=1, realm="TEST.REALM", component="testuser"
    writeUint32BE 1u
    writeUint32BE 1u
    writeCountedString "TEST.REALM"
    writeCountedString "testuser"

    // Credential entry
    // Client principal: name_type=1, num_components=1, realm="TEST.REALM", component="testuser"
    writeUint32BE 1u
    writeUint32BE 1u
    writeCountedString "TEST.REALM"
    writeCountedString "testuser"

    // Server principal
    writeUint32BE 2u  // NT-SRV-INST
    writeUint32BE (uint32 serverNameComponents.Length)
    writeCountedString "TEST.REALM"
    for comp in serverNameComponents do
        writeCountedString comp

    // KeyBlockV4: keytype=18, etype=18, keylen=32, keyvalue
    let keyBytes = Array.init 32 (fun i -> byte (i + 1))
    writeUint16BE 18us
    writeUint16BE 18us
    writeUint16BE 32us
    writeBytes keyBytes

    // Timestamps: authtime, starttime, endtime, renew_till
    writeUint32BE 1700000000u
    writeUint32BE 1700000000u
    writeUint32BE 4102444800u  // far future: 2100-01-01
    writeUint32BE 4102531200u

    // is_skey
    writeByte 0uy

    // tktflags
    writeUint32BE 0u

    // num_addresses = 0
    writeUint32BE 0u

    // num_authdata = 0
    writeUint32BE 0u

    // ticket: a CountedOctetString with some fake BER bytes
    let fakeTicket = Array.init 100 (fun i -> byte (i % 256))
    writeUint32BE (uint32 fakeTicket.Length)
    writeBytes fakeTicket

    // second_ticket: empty
    writeUint32BE 0u

    buf.ToArray()

