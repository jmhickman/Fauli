/// Build a synthetic TgtResult for roundtrip testing.
let private buildTestTgtResult () : TgtResult =
    let key = { enctype = EncryptionType.AES256_CTS_HMAC_SHA1_96
                contents = Array.init 32 (fun i -> byte (i + 1)) }
    let cnameBytes = encodePrincipalName 1 [| "testuser" |] |> parseBer
    { ticketBytes = Array.init 100 (fun i -> byte (i % 256))
      sessionKey = key
      sessionKeyType = 18
      cname = Some cnameBytes
      crealm = Some "TEST.REALM"
      serverTime = Some (DateTime(2035, 1, 1, 12, 0, 0, DateTimeKind.Utc)) }

[<Fact>]
let ``writeCcache produces valid version 4 header`` () =
    let tgt = buildTestTgtResult ()
    let ccache = writeCcache tgt

    // MiniHeader: file_format_version = 0x0504, headerlen = 12
    Assert.Equal(0x05uy, ccache.[0])
    Assert.Equal(0x04uy, ccache.[1])
    Assert.Equal(0x00uy, ccache.[2])
    Assert.Equal(0x0Cuy, ccache.[3])

    // File should be substantial (header + principal + credential + ticket)
    Assert.True(ccache.Length > 100, $"ccache should be >100 bytes but got {ccache.Length}")

[<Fact>]
let ``writeCcache roundtrip: TgtResult -> ccache -> parseCcache`` () =
    let tgt = buildTestTgtResult ()
    let ccache = writeCcache tgt

    match parseCcache ccache with
    | Ok cred ->
        // Session key preserved
        Assert.Equal(18, int cred.sessionKey.enctype)
        Assert.Equal(32, cred.sessionKey.contents.Length)
        for i in 0 .. 31 do
            Assert.Equal(byte (i + 1), cred.sessionKey.contents.[i])

        // Client identity preserved
        Assert.True(cred.clientName = ["testuser"])
        Assert.Equal("TEST.REALM", cred.clientRealm)

        // Server is krbtgt/TEST.REALM (TGT)
        Assert.True(cred.serverName = "krbtgt" :: "TEST.REALM" :: [])
        Assert.Equal("TEST.REALM", cred.serverRealm)

        // Ticket bytes preserved
        Assert.True(cred.ticketBytes.Length = 100)
        Assert.True(cred.ticketBytes = tgt.ticketBytes)

        // Endtime is 24h after serverTime
        match cred.endtime with
        | Some dt ->
            let expected = DateTime(2035, 1, 2, 12, 0, 0, DateTimeKind.Utc)
            Assert.True((dt - expected).TotalSeconds < 3600.0, $"Expected endtime ~{expected} but got {dt}")
        | None -> Assert.Fail("Expected endtime")
    | Error e ->
        Assert.Fail($"parseCcache failed on our own output: {e}")

