[<Fact>]
let ``ccache version parsing is big-endian`` () =
    // Verify that the ccache parser correctly reads big-endian version
    let ccache = buildMinimalCcache ["krbtgt"; "TEST.REALM"]
    // bytes 0-1 should be 0x05, 0x04
    Assert.Equal(0x05uy, ccache.[0])
    Assert.Equal(0x04uy, ccache.[1])

[<Fact>]
let ``ccache key block has correct key bytes`` () =
    let ccache = buildMinimalCcache ["krbtgt"; "TEST.REALM"]
    match parseCcache ccache with
    | Ok cred ->
        // Key bytes should be [1, 2, 3, ..., 32]
        for i in 0 .. 31 do
            Assert.Equal(byte (i + 1), cred.sessionKey.contents.[i])
    | Error e ->
        Assert.Fail($"Expected Ok but got: {e}")

[<Fact>]
let ``ccache unix timestamp converts to DateTime`` () =
    let ccache = buildMinimalCcache ["krbtgt"; "TEST.REALM"]
    match parseCcache ccache with
    | Ok cred ->
        match cred.endtime with
        | Some dt ->
            // endtime was set to a far-future timestamp (year 2100)
            Assert.True(dt.Year > 2090)
        | None -> Assert.Fail("Expected endtime")
    | Error e ->
        Assert.Fail($"Expected Ok but got: {e}")

