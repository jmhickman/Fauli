        Assert.Equal("TEST.REALM", cred.serverRealm)
        Assert.True(cred.ticketBytes.Length > 0)
        Assert.NotNull(cred.endtime)
    | Error e ->
        Assert.Fail($"Expected Ok but got error: {e}")

[<Fact>]
let ``parseCcache rejects empty data`` () =
    match parseCcache [||] with
    | Error InvalidCcacheFormat -> ()
    | Error e -> Assert.Fail($"Expected InvalidCcacheFormat but got: {e}")
    | Ok _ -> Assert.Fail("Expected error for empty data")

[<Fact>]
let ``parseCcache rejects wrong version`` () =
    // Version 3 (not supported) — bytes 0-1 are 0x05 0x03
    let data = [| 0x05uy; 0x03uy; 0x05uy; 0x03uy; 0x00uy; 0x00uy |]
    match parseCcache data with
    | Error InvalidCcacheFormat -> ()
    | Error CcacheVersionNotSupported -> ()
    | Error e -> Assert.Fail($"Expected an error but got: {e}")
    | Ok _ -> Assert.Fail("Expected error for v3 ccache")

[<Fact>]
let ``parseCcache rejects invalid format`` () =
    match parseCcache [| 0xFFuy; 0xFFuy; 0xFFuy; 0xFFuy; 0xFFuy; 0xFFuy |] with
    | Error InvalidCcacheFormat -> ()
    | Error CcacheVersionNotSupported -> ()
    | Error e -> Assert.Fail($"Expected an error but got: {e}")
    | Ok _ -> Assert.Fail("Expected error for invalid data")

