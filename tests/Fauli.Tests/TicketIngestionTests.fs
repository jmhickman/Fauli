[<Fact>]
let ``parseKirbi extracts TGT from minimal KRB-CRED`` () =
    let kirbi = buildMinimalKirbi ["krbtgt"; "TEST.REALM"]

    // Verify it starts with APPLICATION 22 tag
    Assert.Equal(0x76uy, kirbi.[0])

    match parseKirbi kirbi with
    | Ok cred ->
        Assert.Equal(18, int cred.sessionKey.enctype)
        Assert.Equal(32, cred.sessionKey.contents.Length)
        Assert.True(cred.clientName = ["testuser"])
        Assert.Equal(Some "TEST.REALM", cred.clientRealm)
        Assert.True(cred.serverName = ["krbtgt"; "TEST.REALM"])
        Assert.Equal(Some "TEST.REALM", cred.serverRealm)
        Assert.True(cred.ticketBytes.Length > 0)
    | Error e ->
        Assert.Fail($"Expected Ok but got error: {e}")

[<Fact>]
let ``parseKirbi rejects empty data`` () =
    match parseKirbi [||] with
    | Error InvalidKirbiFormat -> ()
    | Error e -> Assert.Fail($"Expected InvalidKirbiFormat but got: {e}")
    | Ok _ -> Assert.Fail("Expected error for empty data")

[<Fact>]
let ``parseKirbi rejects non-KRB-CRED data`` () =
    match parseKirbi [| 0x01uy; 0x02uy; 0x03uy; 0x04uy |] with
    | Error InvalidKirbiFormat -> ()
    | Error (ParseError _) -> ()
    | Error e -> Assert.Fail($"Expected InvalidKirbiFormat but got: {e}")
    | Ok _ -> Assert.Fail("Expected error for invalid data")

[<Fact>]
let ``parseKirbi finds TGT among multiple credentials`` () =
    // Build a kirbi where the TGT has krbtgt as server name
    let kirbi = buildMinimalKirbi ["krbtgt"; "TEST.REALM"]
    match parseKirbi kirbi with
    | Ok cred ->
        Assert.True(List.head cred.serverName = "krbtgt")
    | Error e ->
        Assert.Fail($"Expected Ok but got: {e}")

[<Fact>]
let ``parseKirbi returns NoTgtFound when no krbtgt credential`` () =
    // Build with non-krbtgt server name
    let kirbi = buildMinimalKirbi ["cifs"; "server.test.realm"]
    match parseKirbi kirbi with
    | Error NoTgtFound -> ()
    | Error e -> Assert.Fail($"Expected NoTgtFound but got: {e}")
    | Ok _ -> Assert.Fail("Expected NoTgtFound for non-krbtgt server")

