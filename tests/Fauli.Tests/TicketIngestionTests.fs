/// Build a minimal but structurally valid KRB-CRED (APPLICATION 22) with one
/// TGT credential. Uses etype=0 (NULL) so the cipher field is plaintext.
let private buildMinimalKirbi (serverNameComponents : string list) : byte array =
    // Build a minimal Ticket (APPLICATION 1)
    let ticketRealm = encodeRealm "TEST.REALM"
    let ticketSname = encodePrincipalName 2 [| "krbtgt"; "TEST.REALM" |]
    let ticketEncPart = encodeEncryptedData 18 None (Array.zeroCreate 32)
    let ticket = encodeTicket 5 ticketRealm ticketSname ticketEncPart

    // Build KrbCredInfo
    let keyType = 18  // AES256
    let keyValue = Array.init 32 (fun i -> byte (i + 1))
    let encryptionKey = encodeEncryptionKey keyType keyValue
    let prealm = encodeGeneralString "TEST.REALM"
    let pname = encodePrincipalName 1 [| "testuser" |]

    let serverRealm = encodeGeneralString "TEST.REALM"
    let sname = encodePrincipalName 2 (serverNameComponents |> List.toArray)

    // Build EncKrbCredPart content (SEQUENCE with [0] ticket-info)
    let krbCredInfoSeq =
        encodeSequence
            [| encodeContextConstructed 0 encryptionKey
               encodeContextConstructed 1 prealm
               encodeContextConstructed 2 pname
               encodeContextConstructed 8 serverRealm
               encodeContextConstructed 9 sname |]

    // ticket-info is a SEQUENCE OF KrbCredInfo
    let ticketInfo = encodeSequence [| krbCredInfoSeq |]

    // EncKrbCredPart: [APPLICATION 29] wrapping SEQUENCE { [0] ticket-info }
    let encKrbCredPartContent =
        encodeSequence [| encodeContextConstructed 0 ticketInfo |]
    let encKrbCredPart = encodeApplicationConstructed 29 encKrbCredPartContent

    // EncryptedData: [0] etype=0, [2] cipher (OCTET STRING of EncKrbCredPart)
    let encryptedData =
        encodeSequence
            [| encodeContextConstructed 0 (encodeInteger 0)
               encodeContextConstructed 2 (encodeOctetString encKrbCredPart) |]

    // KRB-CRED: [APPLICATION 22] SEQUENCE {
    //   [0] pvno=5, [1] msg-type=22, [2] tickets, [3] enc-part
    // }
    let ticketsSeq = encodeSequence [| ticket |]
    let krbCredContent =
        encodeSequence
            [| encodeContextConstructed 0 (encodeInteger 5)
               encodeContextConstructed 1 (encodeInteger 22)
               encodeContextConstructed 2 ticketsSeq
               encodeContextConstructed 3 encryptedData |]
    encodeApplicationConstructed 22 krbCredContent

